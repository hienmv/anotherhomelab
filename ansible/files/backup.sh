#!/usr/bin/env bash
# Homelab backup: Kubernetes Secrets + PostgreSQL, encrypted with age. Runs on the admin
# workstation (node-workstation). Plaintext only ever lives in $XDG_RUNTIME_DIR (tmpfs, mode 700, this user).
#
# Usage: backup.sh <out-dir> <age-recipient> <secret> [<secret> ...]   (secret = namespace/name)
set -euo pipefail

out_dir=$1; recipient=$2; shift 2
export KUBECONFIG=${KUBECONFIG:-$HOME/.kube/homelab.yaml}
stamp=$(date +%Y%m%d-%H%M%S)
work=$(mktemp -d "${XDG_RUNTIME_DIR:-/dev/shm}/homelab-backup.XXXXXX")
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/secrets" "$work/postgres"

# Strip server-side fields so the files re-apply cleanly on a new cluster.
clean='del(.metadata.uid, .metadata.resourceVersion, .metadata.creationTimestamp,
          .metadata.managedFields, .metadata.ownerReferences, .metadata.selfLink,
          .metadata.annotations."kubectl.kubernetes.io/last-applied-configuration")'

# 1. Hand-made secrets, one file each (these are what a rebuild needs).
for s in "$@"; do
  ns=${s%%/*}; name=${s#*/}
  kubectl -n "$ns" get secret "$name" -o json | jq "$clean" > "$work/secrets/$ns--$name.json"
done

# 2. Every other Secret too (reference only; most are regenerated by their controllers).
kubectl get secrets -A -o json \
  | jq "{apiVersion: \"v1\", kind: \"List\", items: [.items[]
        | select(.type != \"kubernetes.io/service-account-token\" and .type != \"helm.sh/release.v1\")
        | $clean]}" > "$work/secrets/all-secrets.json"

# 3. PostgreSQL: roles + each application database (custom format, for pg_restore).
pod=$(kubectl -n data get pod -l cnpg.io/cluster=pg,cnpg.io/instanceRole=primary -o name | head -1)
kubectl -n data exec "$pod" -c postgres -- pg_dumpall -U postgres --globals-only > "$work/postgres/globals.sql"
for db in $(kubectl -n data exec "$pod" -c postgres -- psql -U postgres -Atc \
            "select datname from pg_database where not datistemplate and datname <> 'postgres'"); do
  kubectl -n data exec "$pod" -c postgres -- pg_dump -U postgres -Fc "$db" > "$work/postgres/$db.dump"
  head -c 5 "$work/postgres/$db.dump" | grep -q PGDMP || { echo "bad dump: $db" >&2; exit 1; }
  # exact row counts, checked again after a restore (restore.yml)
  kubectl -n data exec "$pod" -c postgres -- psql -U postgres -d "$db" -Atc \
    "select format('select %L, count(*) from %I.%I;', schemaname||'.'||relname, schemaname, relname)
       from pg_stat_user_tables order by 1" \
    | kubectl -n data exec -i "$pod" -c postgres -- psql -U postgres -d "$db" -At -F' ' \
    > "$work/postgres/$db.rows"
done

# 4. Manifest of what is inside (no secret values).
{
  echo "created: $stamp  cluster: $(kubectl config current-context)"
  echo "nodes:"; kubectl get nodes --no-headers -o custom-columns=N:.metadata.name,IP:.status.addresses[0].address | sed 's/^/  /'
  echo "files:"; (cd "$work" && find . -type f ! -name MANIFEST -exec ls -l {} \; | awk '{print "  " $5 "\t" $9}')
} > "$work/MANIFEST"

# 5. Encrypt, then prove it decrypts with the local key.
mkdir -p "$out_dir"; chmod 700 "$out_dir"
file="$out_dir/homelab-$stamp.tar.gz.age"
# write to .partial, rename only after the decrypt check: restore.yml picks the newest *.tar.gz.age
tar -C "$work" -czf - . | age -r "$recipient" -o "$file.partial"
chmod 600 "$file.partial"
count=$(age -d -i "$HOME/.config/sops/age/keys.txt" "$file.partial" | tar -tzf - | grep -c -v '/$')
mv "$file.partial" "$file"

cat "$work/MANIFEST"
echo "encrypted: $file ($(du -h "$file" | cut -f1), $count files, decrypt check OK)"
echo "BACKUP_FILE=$file"
